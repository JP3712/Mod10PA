def read_penguin_row(row_number):
    penguin_row = ""
    # Exception handling try statement
    try:
      # open the CSV file and skip the header row
      with open("PalmerPenguins.csv", "r") as penguin_file:
          penguin_file.readline()

          current_row = 1

          # search for the requested data row
          for row in penguin_file:
              if current_row == row_number:
                  penguin_row = row.strip()
                  break

              current_row += 1
    # Exception handling for CSV file
    except FileNotFoundError:
      print("Error: PalmerPenguins.csv was not found.")

    # Raise exception for missing observation
    if penguin_row == "":
      raise ValueError(f"Penguin observation {row_number} "
                       f"could not be retrieved.")
    # return the requested row as a string
    return penguin_row

# User defined functions
def calculate_percentage(count, total):
  """This function is used to calculate the penguin species percentages."""
  return count / total * 100

def classify_species(percent):
  """This function is used to calculate the penguin species size."""
  if percent < 25:
    return "small"
  elif (percent >= 25) and (percent < 40):
    return "medium"
  else:
    return "large"

def get_position_description(
    selected_species,
    largest_species,
    smallest_species
):
  """This function determines species relative size position among groups."""
  if selected_species == largest_species:
    return "largest"
  elif selected_species == smallest_species:
    return "smallest"
  else:
    return "middle-sized"

def display_species_statistics(names, counts, percentages):
  """This function displays species statistics."""
  for index, species in enumerate(names):
    print(f"{species}: {counts[index]} {percentages[index]:.2f}%")
  print()

